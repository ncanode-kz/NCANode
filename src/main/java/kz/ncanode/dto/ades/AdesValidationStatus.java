package kz.ncanode.dto.ades;

/**
 * Итоговый статус проверки AdES-подписи (упрощённый ETSI EN 319 102-1).
 */
public enum AdesValidationStatus {
    /** Подпись действительна. */
    VALID,
    /** Подпись недействительна (крипто-ошибка, отзыв до подписи и т.п.). */
    INVALID,
    /** Не удалось однозначно определить (нет цепочки, нет данных отзыва, метка невалидна). */
    INDETERMINATE
}
